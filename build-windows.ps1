$ErrorActionPreference = 'Stop'

if (-not (Get-Command gradle -ErrorAction SilentlyContinue)) {
  throw 'Gradle 8.10.2+ was not found. Install Gradle and JDK 17, then retry.'
}

gradle packageReleaseExe createDistributable --stacktrace
if ($LASTEXITCODE -ne 0) {
  throw "Gradle build failed with exit code $LASTEXITCODE"
}

$appBase = Join-Path $PWD 'build/compose/binaries/main/app'
if (-not (Test-Path $appBase)) {
  throw "Compose app-image directory was not created: $appBase"
}

$javaCandidates = @(Get-ChildItem -Path $appBase -Filter 'java.exe' -File -Recurse |
  Where-Object { $_.FullName -match '[\\/]runtime[\\/]bin[\\/]java\.exe$' })
if ($javaCandidates.Count -eq 0) {
  Write-Host 'Files produced under app-image directory:'
  Get-ChildItem -Path $appBase -Recurse -File | Select-Object -ExpandProperty FullName | Write-Host
  throw 'Bundled runtime/bin/java.exe was not generated by createDistributable.'
}

$validImage = $null
foreach ($candidate in $javaCandidates) {
  $candidateImage = $candidate.Directory.Parent.Parent
  $candidateLauncher = Join-Path $candidateImage.FullName 'NetworkToolkit.exe'
  if (Test-Path $candidateLauncher) {
    $validImage = $candidateImage.FullName
    & $candidate.FullName -version
    if ($LASTEXITCODE -ne 0) { throw 'Bundled Java runtime failed its startup check.' }
    break
  }
}
if (-not $validImage) {
  Write-Host 'Found Java candidates:'
  $javaCandidates | Select-Object -ExpandProperty FullName | Write-Host
  throw 'Found bundled Java, but could not pair it with NetworkToolkit.exe.'
}

Write-Host "Verified self-contained app image: $validImage" -ForegroundColor Green
